#!/usr/bin/env python3
"""Generate crt0.asm for the clean-room HLE BIOS image (M0).

Nothing here is copied from the SNK BIOS: only the *structure* the hardware
and the emulator core require (vector-table layout, the swi dispatch shape,
the user-vector chaining) is reproduced. All of it is public contract from
the SDK docs / the TLCS-900 architecture.

Image map (64 KiB, linked at 0xFF0000):
  0xFF0000  f_code       boot + dispatcher + ISRs + stubs
  0xFFFE00  SYSCALL_TBL  32 pointers, swi 1 vector index -> stub
  0xFFFF00  INT_VECTOR   60 hardware vectors (reset/swi/IRQ)
"""

import os

# --- user vector table (RAM, 0x6FB8) : which hardware IRQ index maps to
#     which 4-byte slot. Source: ngpcspec.txt "User Program Interrupt Vectors"
#     (the "MICRO DMA START VECTOR" column IS the hardware index).
UVT = 0x6FB8
USER_SLOT = {
    3: UVT + 0 * 4,    # SWI 3
    4: UVT + 1 * 4,    # SWI 4
    5: UVT + 2 * 4,    # SWI 5
    6: UVT + 3 * 4,    # SWI 6
    10: UVT + 4 * 4,   # RTC alarm      (0x6FC8)
    11: UVT + 5 * 4,   # VBlank         (0x6FCC)
    12: UVT + 6 * 4,   # Z80            (0x6FD0)
    16: UVT + 7 * 4,   # Timer 0        (0x6FD4)
    17: UVT + 8 * 4,   # Timer 1
    18: UVT + 9 * 4,   # Timer 2
    19: UVT + 10 * 4,  # Timer 3
    24: UVT + 11 * 4,  # Serial TX      (0x6FE4)
    25: UVT + 12 * 4,  # Serial RX      (0x6FE8)
    29: UVT + 14 * 4,  # End micro-DMA 0 (0x6FF0)
    30: UVT + 15 * 4,  # End micro-DMA 1
    31: UVT + 16 * 4,  # End micro-DMA 2
    32: UVT + 17 * 4,  # End micro-DMA 3
}

# The two serial vectors do NOT trampoline to a user slot: the COM rings belong to
# the BIOS, and the retail BIOS takes these over too. CROSS-WIRED versus the SDK's
# names -- 0x18 ("INTTX0") receives, 0x19 ("INTRX0") transmits. See machine.hpp.
SERIAL_ISR = {0x18: "_isr_ser_rx", 0x19: "_isr_ser_tx"}

HW_TABLE_SLOTS = 60      # 0xFFFF00 .. 0xFFFFF0, 4 bytes each
SYSCALL_SLOTS = 32       # 0xFFFE00 .., swi 1 dispatch indices 0..0x1A used

FONT_FG = 3              # 2bpp pixel index for a lit pixel (default palette)
FONT_BG = 0


FONT_BIN = os.path.join(os.path.dirname(os.path.abspath(__file__)), "font_2bpp.bin")


def build_font_2bpp():
    """The clean-room 8x8 font, expanded to the K2GE 2bpp CHAR-RAM tile format:
    256 tiles x 16 bytes, each row a big-endian word (pixel 0 in the high bits),
    matching the retail SYSFONTSET layout. Returns 0x1000 bytes to preload at
    0xA000.

    Read from the baked font_2bpp.bin, which is what the shipped bios_hle.bin
    was built from. Pillow is NOT a dependency of this module -- it is optional
    everywhere else in the tree (see core/frame_diff.py) and importing it here
    made gen() unrunnable on a bare CI box. Regenerate the .bin with
    `python gen_crt0.py --regen-font`, which needs Pillow and rasterises its
    public-domain default face."""
    with open(FONT_BIN, "rb") as f:
        font = f.read()
    assert len(font) == 0x1000, f"{FONT_BIN}: {len(font)} bytes, expected 0x1000"
    return font


def rasterise_font_2bpp():
    """Rebuild the font bytes from the written-down glyphs in font_glyphs.py.

    ⛔ IT USED TO CALL PILLOW, AND THAT WAS THE BUG. `ImageFont.load_default()`
    is about eleven pixels tall; drawn into an 8x8 box every glyph lost its
    bottom stroke, so the BIOS handed games an `E` shaped like an `F` and an `L`
    with no foot. It also made the SHIPPED IMAGE depend on which Pillow the
    build machine had installed. The glyphs are a table now: no dependency, and
    the same bytes on every machine.
    """
    # By file path, not by sys.path: this module is imported from the test
    # suite as well as run from its own directory.
    import importlib.util
    here = os.path.dirname(os.path.abspath(__file__))
    spec = importlib.util.spec_from_file_location(
        "font_glyphs", os.path.join(here, "font_glyphs.py")
    )
    font_glyphs = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(font_glyphs)
    glyph_rows = font_glyphs.glyph_rows

    out = bytearray()
    for code in range(256):
        rows = glyph_rows(code) if 0x20 <= code < 0x7F else [" " * 8] * 8
        for row in rows:
            word = 0
            for x in range(8):
                word = (word << 2) & 0xFFFF
                word |= FONT_FG if row[x] == "#" else FONT_BG
            # ⛔ LOW BYTE FIRST. A CHAR-RAM row is a 16-bit word stored
            # little-endian, so the byte at the lower address carries the RIGHT
            # half of the row. Writing the halves the other way round swaps them
            # on screen: every glyph came out as its own two halves exchanged,
            # which reads as a font that is nearly right and completely
            # illegible. Checked against the retail BIOS's own 'P' at tile 0x50:
            #   retail  f0 3f | 0c 30 | 0c 30 | f0 3f | 00 30 ...
            out.append(word & 0xFF)          # pixels 4-7
            out.append((word >> 8) & 0xFF)   # pixels 0-3
    assert len(out) == 0x1000
    return bytes(out)


# The system-call table, BY VECTOR NUMBER FROM SYSTEM.INC -- which is the
# authority. A second doc put FLASHPROTECT on 9; 9 is ALARMSET, so following it
# would have had a game's alarm irreversibly protect a flash block instead.
# tests/test_hle_bios_image.py pins these numbers.
SC_STUB = {
    0x00: "_sc_shutdown",      # SHUTDOWN      -> the console switched off
    0x02: "_sc_rtcget",   # RTCGET            -> copy the clock into XHL3 (Ganbare)
    0x04: "_sc_intlvset", # INTLVSET          -> set INTxx priority (Card Fighters Clash 2)
    0x05: "_sc_sysfontset",    # SYSFONTSET    -> font into CHAR RAM, with its palette
    0x06: "_sc_flashwrite",   # FLASHWRITE    -> program the save into the cartridge
    0x07: "_sc_flashallers",  # FLASHALLERS   -> erase the whole chip
    0x08: "_sc_flashers",     # FLASHERS      -> erase one block, by NUMBER
    0x09: "_sc_alarmset",      # ALARMSET      -> RTC alarm (NOT flash protect)
    0x0B: "_sc_alarmdownset",  # ALARMDOWNSET  -> same registers, power-on alarm
    0x0D: "_sc_flashprotect",  # FLASHPROTECT  -> make blocks read-only (irreversible)
    0x0E: "_sc_gemodeset",     # GEMODESET     -> K1GE / K2GE display mode
    0x10: "_sc_cominit",       # COMINIT
    0x11: "_sc_comsendstart",  # COMSENDSTART
    0x12: "_sc_comrecvstart",  # COMRECIVESTART
    0x13: "_sc_comcreatedata", # COMCREATEDATA    -> queue one byte
    0x14: "_sc_comgetdata",    # COMGETDATA       -> pop one byte (or 'empty')
    0x15: "_sc_comonrts",      # COMONRTS         -> ready to receive
    0x16: "_sc_comoffrts",     # COMOFFRTS        -> hold the peer off
    0x17: "_sc_comsendstatus", # COMSENDSTATUS    -> bytes still queued
    0x18: "_sc_comrecvstatus", # COMRECIVESTATUS  -> bytes waiting
    0x19: "_sc_combufsend",    # COMCREATEBUFDATA -> queue a block
    0x1A: "_sc_combufget",     # COMGETBUFDATA    -> pop a block
}


def card_block_offsets(capacity):
    """The card's blocks, in order, as offsets -- the SDK's own numbering. 64 KiB all
    the way up, then the last 64 KiB split 32 / 8 / 8 / 16. The block NUMBER a game
    passes indexes this list, which is why the table is per-card: block 17 is 0xFA000
    on an 8 Mbit card and 0x110000 on a 16 Mbit one. Same map as
    Machine::flash_build_blocks -- two copies of one truth is how they drift apart, so
    tests/test_hle_bios_flash.py checks this list against the core's."""
    out = []
    off = 0
    while off + 0x10000 <= capacity - 0x10000:
        out.append(off)
        off += 0x10000
    top = capacity - 0x10000
    return out + [top, top + 0x8000, top + 0xA000, top + 0xC000]


def gen():
    out = []
    A = out.append
    A(";***************************************************************")
    A(";  NgpCraft Emulator - clean-room HLE BIOS image (M0)  [GENERATED]")
    A(";  Loaded via ngpc_load_bios when no real bios.bin is present.")
    A(";  Clean-room: reproduces the hardware/SDK CONTRACT, not SNK bytes.")
    A(";***************************************************************")
    A("\t$MAXIMUM")
    A("\tmodule\tbios_hle")
    A("")
    A("\tpublic\t_boot")
    A("")
    A(";===============================================================")
    A("f_code\tsection code large align=1,1")
    A(";===============================================================")
    A("")
    A("; --- RESET / power-on : hw vector slot 0 (0xFFFF00) ---")
    A("_boot:")
    A("\tld\txiy, _uvt_stub          ; 45 <stub>   ] ANCHOR the core's")
    A("\tld\txix, 0x00006fb8         ; 44 B8 6F..  ] seed_user_vector_table scans")
    A("\tld\tbc, 18")
    A("_uvt_fill:")
    A("\tldl\t(xix+), xiy")
    A("\tdjnz\tbc, _uvt_fill")
    A("\tldw\t(0x006c7a), 0xa5a5     ; 'booted once' marker")
    A("\t; The INTxx shadows (0x6C24..0x6C2B) are deliberately NOT seeded here. Seeding")
    A("\t; them from the registers was tried and measured: this code runs during the")
    A("\t; warm-up, BEFORE the hand-off writes INTE45, so it copied zeros -- and the")
    A("\t; retail BIOS leaves them at zero too (89 of 90 ROMs). Zero is the match.")
    A("\t; preload the clean-room font into CHAR RAM (the warm-up captures it,")
    A("\t; the hand-off installs it) -- games that SYSFONTSET find it present.")
    A("\tld\txix, _font_data")
    A("\tld\txiy, 0x0000a000")
    A("\tld\tbc, 0x0400              ; 0x1000 bytes / 4")
    A("_font_copy:")
    A("\tldl\txwa, (xix+)")
    A("\tldl\t(xiy+), xwa")
    A("\tdjnz\tbc, _font_copy")
    A("_boot_idle:")
    A("\thalt")
    A("\tjr\t_boot_idle")
    A("")
    A("; --- default user-vector stub (bare RETI) ---")
    A("_uvt_stub:")
    A("\treti")
    A("")
    A("; --- generic unused-interrupt stub ---")
    A("_reti:")
    A("\treti")
    A("")
    A("; --- swi 1 : BIOS system-call trap. Dispatch through SYSCALL_TBL, same as")
    A(";  the SDK's SYSTEM_CALL wrapper -- some games (Card Fighters Clash 2) call")
    A(";  INTLVSET via `swi 1` directly, not the wrapper. ldf 3 makes W == RW3.")
    A(";  We emulate `call (stub)` with a push/RET (asm900 rejects `call (reg)`),")
    A(";  the stub returns via RET, then we RETI back to the caller.")
    A(";")
    A(";  !! THE DISPATCHER MUST NOT EAT THE ARGUMENTS. This used to do its table")
    A(";  lookup in XHL and park the return address in XDE -- but XHL3 and XDE3 ARE")
    A(";  arguments: FLASHWRITE takes the source in XHL3 and the offset in XDE3,")
    A(";  RTCGET takes its buffer in XHL3. So a save through `swi 1` programmed from")
    A(";  the dispatcher's own address, and every byte went nowhere. The SDK wrapper")
    A(";  gets this right by using XIX; we do the same, and park what XIX cannot hold")
    A(";  in BIOS work RAM. Only W (the vector number, already consumed) is clobbered.")
    A("SWI_SAVED_XIX\tequ\t0x006c44")
    A("SWI_STUB\tequ\t0x006c48")
    A("_swi1:")
    A("\tldf\t3                     ; W = RW3 = vector index")
    A("\tldl\t(SWI_SAVED_XIX), xix   ; the game's XIX -- restored before the stub runs")
    A("\tadd\tw, w")
    A("\tadd\tw, w                   ; W = index * 4")
    A("\tld\txix, 0x00fffe00")
    A("\tldl\txix, (xix+w)           ; XIX = SYSCALL_TBL[index]")
    A("\tldl\t(SWI_STUB), xix")
    A("\tld\txix, _swi1_after        ; return address, pushed UNDER the target")
    A("\tpush\txix")
    A("\tldl\txix, (SWI_STUB)")
    A("\tpush\txix                   ; target on top: RET jumps to the stub")
    A("\tldl\txix, (SWI_SAVED_XIX)")
    A("\tret                            ; -> stub (returns via RET to _swi1_after)")
    A("_swi1_after:")
    A("\treti")
    A("")
    A(";  Syscall stubs reached by a DIRECT table CALL -- the SDK's SYSTEM_CALL")
    A(";  wrapper (calr, not swi 1): it does ldf 3 then `call (0xFFFE00 + RW3*4)`,")
    A(";  so a stub runs in bank 3 and returns via RET. Commercial COM-heavy games")
    A(";  (Nige-Ron-Pa, Koi Koi, KOF-BdP) DRAIN the serial RX with COMGETDATA until")
    A(";  RA3==1 ('no more data'); with no cable the real BIOS returns 1 at once.")
    A("_sc_ret:")
    A("\tret                            ; default: leave registers as-is")
    A("_sc_nodata:")
    A("\tldw\twa, 0x0101              ; RA3=1 (and RW3=1): 'buffer empty / no data'")
    A("\tret")
    A("_sc_zero:")
    A("\tldw\twa, 0x0000              ; RWA3=0: COM*STATUS = no error, no data")
    A("\tret")
    A(";  RTCGET: copy 7 packed-BCD clock bytes (year,month,day,hour,min,sec,")
    A(";  weekday) from the RTC I/O regs 0x91-0x97 into the caller's buffer at")
    A(";  XHL3. The core routes 0x90-0x9A reads to its seeded RTC. WA/XHL preserved.")
    A("_sc_rtcget:")
    A("\tpush\twa")
    A("\tpush\txhl")
    for reg in range(0x91, 0x98):
        A(f"\tldb\ta, ({reg:#04x})")
        A("\tldb\t(xhl+), a")
    A("\tpop\txhl")
    A("\tpop\twa")
    A("\tret")
    A(";  INTLVSET: set interrupt source's priority in the INTxx I/O regs. Bank 3:")
    A(";  C=source(0..9), B=level. MEASURED from the retail BIOS (5 games): the")
    A(";  written nibble = 0x08 | min(level&7,5) -- the 0x08 is the ENABLE bit the")
    A(";  Python ref omits. Even source -> low nibble, odd -> high; reg from table.")
    A(";  ---------------- THE SAVE: a real flash driver, not a stub ----------------")
    A(";  A Neo Geo Pocket has no save RAM: a game saves by ERASING a block of its own")
    A(";  cartridge and PROGRAMMING its slot back in, and it asks the BIOS to do it.")
    A(";  These four vectors used to fall through to `_sc_ret`, which left RA3 holding")
    A(";  the CARD NUMBER the caller passed (0) -- read back as SYS_SUCCESS. So every")
    A(";  save reported success and wrote NOTHING. A save that fails loudly is bad; a")
    A(";  save that fails silently is how a player loses a file and never knows why.")
    A(";")
    A(";  So the driver is the real thing: the AMD/Fujitsu command cycles at the cart")
    A(";  window, which is exactly what the chip in cpp/src/memory.cpp implements.")
    A(";      unlock  AA @ 0x205555 . 55 @ 0x202AAA . then")
    A(";              A0 @ 0x205555  program: the NEXT write IS the data")
    A(";              80 . unlock again . 30 @ block  erase that block")
    A(";              80 . unlock again . 10 @ 5555   erase the whole chip")
    A(";              9A . unlock again . 9A @ block  protect it (irreversible)")
    A(";  After an erase the chip answers ONE read and is memory again -- that read is")
    A(";  what a driver's status poll consumes, and we MUST consume it too: leave it")
    A(";  pending and the game's next instruction fetch from the cart reads 0xFF.")
    A(";")
    A(";  TWO SLOTS, AND THE SECOND ONE IS NOT ALWAYS EMPTY. Card 0 is 0x200000 and")
    A(";  card 1 is 0x800000. On a 2 MiB cartridge that second window is the")
    A(";  DEVELOPMENT slot and a production console has nothing in it -- but a 4 MiB")
    A(";  cartridge is TWO DIES and the second one lives exactly there. Measured: with")
    A(";  Metal Slug 2nd Mission, Densha de Go! 2 or SvC Match of the Millennium in the")
    A(";  slot, the retail BIOS writes 0x6C59 = 3. Refusing card 1 outright -- which is")
    A(";  what this driver did -- fails a save on the very carts that have two chips.")
    A(";  So the test is not the card NUMBER but whether that slot holds a cartridge,")
    A(";  which is precisely what the card-type byte says.")
    A("CARD_TYPE0\tequ\t0x006c58")
    A("UNLOCK1_CARD0\tequ\t0x00205555      ; +0x600000 for card 1")
    A("UNLOCK_DELTA\tequ\t0x2aab           ; 0x5555 - 0x2AAA")

    def unlock2():
        """AA @ 5555, 55 @ 2AAA -- the two cycles that open every command.

        Addressed through XIY (= this card's 0x5555) instead of an absolute, so the
        same code drives either die. The second unlock address is one displacement
        away, which saves carrying a second pointer."""
        A("\tldb\ta, 0xaa")
        A("\tldb\t(xiy), a")
        A("\tldb\ta, 0x55")
        A("\tldb\t(xiy-UNLOCK_DELTA), a")

    def unlock(prefix):
        """...followed by the command byte at 5555."""
        unlock2()
        A(f"\tldb\ta, {prefix}")
        A("\tldb\t(xiy), a")

    def card_slot(tag):
        """RA3 (0 or 1) -> XIY = that card's unlock address, and refuse a slot with no
        cartridge in it. Written inline per stub rather than as a shared exit: `jr` is
        a SHORT relative branch and the block tables push the stubs apart -- a shared
        label assembles until it doesn't (ASM900-Error-227)."""
        A("\tpush\txde")
        A("\tldl\txiy, UNLOCK1_CARD0")
        A("\tcp\ta, 0")
        A(f"\tjr\tz, _{tag}_slot0")
        A("\tcp\ta, 1")
        A(f"\tjr\tnz, _{tag}_no_card")
        A("\tldl\txde, 0x00600000         ; card 1 sits 6 MiB further up")
        A("\taddl\txiy, xde")
        A(f"_{tag}_slot0:")
        A("\tldl\txde, 0")
        A("\tldb\te, a                    ; card-type byte is 0x6C58 + card")
        A("\tpush\txhl")
        A("\tldl\txhl, CARD_TYPE0")
        A("\taddl\txhl, xde")
        A("\tldb\te, (xhl)                ; ...and E now holds that card's TYPE")
        A("\tpop\txhl")
        A("\tcp\te, 0")
        A(f"\tjr\tz, _{tag}_no_card")
        A("\tldb\t(FL_CARD), a           ; the slot this call is for")
        A("\tpop\txde")
        A(f"\tjr\t_{tag}_card_ok")
        A(f"_{tag}_no_card:")
        A("\tpop\txde")
        A("\tldb\ta, 0xff                 ; nothing in that slot")
        A("\tret")
        A(f"_{tag}_card_ok:")

    A(";  Block number -> absolute address. A game erases by BLOCK NUMBER, and the")
    A(";  number->address table is the CARD's (SDK FlashMem.txt / BLOCK_NO.INC), so it")
    A(";  is chosen by that card's type byte -- 0x6C58 for card 0, 0x6C59 for card 1,")
    A(";  the same bytes the retail BIOS reads. The tables hold card 0's addresses;")
    A(";  card 1 is the same map 6 MiB further up. In: B = block, FL_CARD = the slot.")
    A(";  Out: XDE = address, A = 0 ok / 0xFF bad.")
    A("FL_CARD\tequ\t0x006c4c              ; which slot the call in flight is for")
    A("_fl_block_addr:")
    A("\tpush\txhl")
    A("\tldl\txde, 0")
    A("\tldb\ta, (FL_CARD)")
    A("\tldb\te, a")
    A("\tldl\txhl, CARD_TYPE0")
    A("\taddl\txhl, xde")
    A("\tldb\ta, (xhl)                 ; this card's type")
    A("\tpop\txhl")
    A("\tcp\ta, 1")
    A("\tjr\tz, _flba_4m")
    A("\tcp\ta, 2")
    A("\tjr\tz, _flba_8m")
    A("\tcp\ta, 3")
    A("\tjr\tz, _flba_16m")
    A("\tldb\ta, 0xff                 ; card type 0: no cartridge")
    A("\tret")
    A("_flba_4m:")
    A("\tldl\txhl, _blk_4m")
    A("\tldb\ta, 11")
    A("\tjr\t_flba_go")
    A("_flba_8m:")
    A("\tldl\txhl, _blk_8m")
    A("\tldb\ta, 19")
    A("\tjr\t_flba_go")
    A("_flba_16m:")
    A("\tldl\txhl, _blk_16m")
    A("\tldb\ta, 35")
    A("_flba_go:")
    A("\tcp\tb, a")
    A("\tjr\tnc, _flba_bad            ; block past the end of this card")
    A("\tldl\txde, 0")
    A("\tldb\te, b")
    A("\tsll\t2, e                    ; 4 bytes per entry (35 blocks max -> 140)")
    A("\taddl\txhl, xde")
    A("\tldl\txde, (xhl)")
    A("\tldb\ta, (FL_CARD)")
    A("\tcp\ta, 1")
    A("\tjr\tnz, _flba_ok")
    A("\tpush\txhl")
    A("\tldl\txhl, 0x00600000         ; the second die's window")
    A("\taddl\txde, xhl")
    A("\tpop\txhl")
    A("_flba_ok:")
    A("\tldb\ta, 0")
    A("\tret")
    A("_flba_bad:")
    A("\tldb\ta, 0xff")
    A("\tret")
    A(";  FLASHERS (8): erase one block. In: RA3 = card, RB3 = block.")
    A("_sc_flashers:")
    card_slot("fe")
    A("\tpush\txhl")
    A("\tpush\txde")
    A("\tcalr\t_fl_block_addr")
    A("\tcp\ta, 0")
    A("\tjr\tnz, _fe_bad")
    unlock("0x80")
    unlock2()
    A("\tldb\ta, 0x30                 ; erase the block containing this address")
    A("\tldb\t(xde), a")
    A(";  AND THEN IT WAITS, because the chip is BUSY -- about ten milliseconds for")
    A(";  an 8 KB block, during which the window answers status instead of contents.")
    A(";  This used to be a single read, 'consume the chip's one-shot done', which was")
    A(";  only ever true of a model where an erase costs nothing. Against a chip that")
    A(";  takes time, that read returns status and the routine walks off with the block")
    A(";  still erasing. DQ5 is the chip saying it gave up -- without it, a poll on a")
    A(";  block that cannot erase never ends.")
    A("\tpush\txiz")
    A("\tldl\txiz, 0                  ; the poll's own ceiling: DQ5 may never come")
    A("_fe_poll:")
    A("\tldb\ta, (xde)")
    A("\tcp\ta, 0xff                  ; blank yet?")
    A("\tjr\tz, _fe_erased")
    A("\tbit\t5, (xde)                ; DQ5, if this part has it")
    A("\tjr\tnz, _fe_gave_up")
    A("\tincl\t1, xiz")
    A("\tcpl\txiz, 0x001fffff         ; same ceiling as the AMD stub the games ship")
    A("\tjr\tnz, _fe_poll")
    A("_fe_gave_up:")
    A("\tldb\ta, (xde)                ; one last look before believing it")
    A("\tcp\ta, 0xff")
    A("\tjr\tz, _fe_erased")
    A("\tldb\ta, 0xf0                 ; reset the chip, then say the erase failed")
    A("\tldb\t(xiy), a")
    A("\tpop\txiz")
    A("\tpop\txde")
    A("\tpop\txhl")
    A("\tldb\ta, 0xff")
    A("\tret")
    A("_fe_erased:")
    A("\tpop\txiz")
    A("\tpop\txde")
    A("\tpop\txhl")
    A("\tldb\ta, 0                    ; SYS_SUCCESS")
    A("\tret")
    A("_fe_bad:")
    A("\tpop\txde")
    A("\tpop\txhl")
    A("\tldb\ta, 0xff")
    A("\tret")
