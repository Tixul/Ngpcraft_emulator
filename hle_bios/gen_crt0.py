    A("\tldl\txix, COM_TXRING")
    A("\tldl\txiy, COM_TXCNT")
    A("\tldl\txde, COM_TXHEAD")
    A("\tcalr\t_ring_put")
    A("\tpop\txde")
    A("\tpop\txiy")
    A("\tpop\txix")
    A("\tret")
    A(";  COMGETDATA (0x14): pop one byte into RB3. RA3 = 0 / 1 (COM_BUF_EMPTY).")
    A(";  Drain loops spin until RA3 == 1, so 'empty' must be exact -- and RW3 is set")
    A(";  to 1 with it, which is what the SDK wrapper's callers compare against.")
    A("_sc_comgetdata:")
    A("\tpush\txix")
    A("\tpush\txiy")
    A("\tpush\txde")
    A("\tldl\txix, COM_RXRING")
    A("\tldl\txiy, COM_RXCNT")
    A("\tldl\txde, COM_RXTAIL")
    A("\tcalr\t_ring_get")
    A("\tpop\txde")
    A("\tpop\txiy")
    A("\tpop\txix")
    A("\tcp\ta, 0")
    A("\tjr\tz, _cgd_done")
    A("\tldw\twa, 0x0101               ; RA3=1 and RW3=1: the drain loop's exit")
    A("_cgd_done:")
    A("\tret")
    A(";  COMSENDSTATUS (0x17) / COMRECIVESTATUS (0x18): RWA3, low byte = how many")
    A(";  bytes are in that buffer (serial.h COM_COUNT_MASK); high bits = errors,")
    A(";  which we never raise -- the cable is a byte pipe with no framing to get wrong.")
    A("_sc_comsendstatus:")
    A("\tldb\tw, 0")
    A("\tldb\ta, (COM_TXCNT)")
    A("\tret")
    A("_sc_comrecvstatus:")
    A("\tldb\tw, 0")
    A("\tldb\ta, (COM_RXCNT)")
    A("\tret")
    A(";  COMCREATEBUFDATA (0x19): queue RB3 bytes from XHL3. RB3 = how many did NOT")
    A(";  fit. COMGETBUFDATA (0x1A): pop up to RB3 bytes into XHL3, RB3 = shortfall.")
    A("_sc_combufsend:")
    A("\tpush\txix")
    A("\tpush\txiy")
    A("\tpush\txde")
    A("\tpush\txhl")
    A("\tldl\txix, COM_TXRING")
    A("\tldl\txiy, COM_TXCNT")
    A("\tldl\txde, COM_TXHEAD")
    A("_cbs_loop:")
    A("\tcp\tb, 0")
    A("\tjr\tz, _cbs_done")
    A("\tldb\ta, (xiy)")
    A("\tcp\ta, 64")
    A("\tjr\tnc, _cbs_done             ; full: RB3 keeps the remainder")
    A("\tpush\txbc")
    A("\tldb\tb, (xhl+)                ; the next source byte, into the ring's argument")
    A("\tcalr\t_ring_put")
    A("\tpop\txbc")
    A("\tdecb\t1, b")
    A("\tjr\t_cbs_loop")
    A("_cbs_done:")
    A("\tpop\txhl")
    A("\tpop\txde")
    A("\tpop\txiy")
    A("\tpop\txix")
    A("\tldb\ta, 0")
    A("\tret")
    A("_sc_combufget:")
    A("\tpush\txix")
    A("\tpush\txiy")
    A("\tpush\txde")
    A("\tpush\txhl")
    A("\tldl\txix, COM_RXRING")
    A("\tldl\txiy, COM_RXCNT")
    A("\tldl\txde, COM_RXTAIL")
    A("_cbg_loop:")
    A("\tcp\tb, 0")
    A("\tjr\tz, _cbg_done")
    A("\tldb\ta, (xiy)")
    A("\tcp\ta, 0")
    A("\tjr\tz, _cbg_done              ; empty: RB3 keeps the shortfall")
    A("\tpush\txbc")
    A("\tcalr\t_ring_get                ; B = the byte")
    A("\tldb\ta, b")
    A("\tpop\txbc")
    A("\tldb\t(xhl+), a")
    A("\tdecb\t1, b")
    A("\tjr\t_cbg_loop")
    A("_cbg_done:")
    A("\tpop\txhl")
    A("\tpop\txde")
    A("\tpop\txiy")
    A("\tpop\txix")
    A("\tldb\ta, 0")
    A("\tret")
    A(";  INTLVSET (0x04): set an interrupt source's priority. Bank 3: C = source (0-9),")
    A(";  B = level. The written nibble is 0x08 | min(level & 7, 5) -- the 0x08 is the")
    A(";  ENABLE bit, measured off the retail BIOS on five games and omitted by the")
    A(";  Python reference model.")
    A(";")
    A(";  !! AND THE REGISTER IS NOT THE SOURCE OF TRUTH -- ITS SHADOW IN RAM IS.")
    A(";  The BIOS keeps a copy of every INTxx register in its work RAM, updates THAT,")
    A(";  and writes the whole byte out. Measured, ten sources x two levels: with")
    A(";  INTE45 (0x71) sitting at 0xDC from the hand-off, INTLVSET(source=1, level=3)")
    A(";  leaves it at 0xB0 -- NOT 0xBC. Read-modify-write of the register would have")
    A(";  kept that 0xC; the retail BIOS discards it, because it never looks at the")
    A(";  register at all. Reading the register back was our bug: it preserved a nibble")
    A(";  silicon would have lost.")
    A(";  source -> shadow:  0,1 -> 0x6C24,0x6C25 | 2,3 -> 0x6C27 | 4,5 -> 0x6C28")
    A(";                     6,7 -> 0x6C2A        | 8,9 -> 0x6C2B")
    A("_sc_intlvset:")
    A("\tpush\txhl")
    A("\tpush\txde")
    A("\tpush\txix")
    A("\tcp\tc, 0x0a")
    A("\tjr\tnc, _intlv_done         ; source > 9: no INTxx register written")
    A("\tldb\ta, b")
    A("\tand\ta, 0x07")
    A("\tcp\ta, 0x06")
    A("\tjr\tc, _intlv_cap")
    A("\tldb\ta, 0x05                ; cap level at 5 (retail BIOS)")
    A("_intlv_cap:")
    A("\tor\ta, 0x08                 ; nibble = 0x08(enable) | level")
    A("\tldl\txde, 0")
    A("\tldl\txhl, _intlv_shadow")
    A("\tldb\te, (xhl+c)")
    A("\tldl\txix, 0x00006c00")
    A("\taddl\txix, xde              ; XIX = this register's shadow byte")
    A("\tldl\txde, 0")
    A("\tldl\txhl, _intlv_reg")
    A("\tldb\te, (xhl+c)             ; XDE = the INTxx I/O address")
    A("\tldb\tl, (xix)               ; the shadow -- what the BIOS believes is in there")
    A("\tbit\t0, c")
    A("\tjr\tz, _intlv_lo            ; even source -> low nibble")
    A("\tsll\t4, a                   ; odd source -> high nibble")
    A("\tand\tl, 0x0f")
    A("\tjr\t_intlv_or")
    A("_intlv_lo:")
    A("\tand\tl, 0xf0")
    A("_intlv_or:")
    A("\tor\tl, a")
    A("\tldb\t(xix), l               ; the shadow is updated first...")
    A("\tldb\t(xde), l               ; ...and the whole byte goes to the register")
    A("_intlv_done:")
    A("\tpop\txix")
    A("\tpop\txde")
    A("\tpop\txhl")
    A("\tret")
    A("_intlv_reg:")
    A("\tdb\t0x70,0x71,0x73,0x73,0x74,0x74,0x79,0x79,0x7a,0x7a")
    A("_intlv_shadow:                 ; low byte of the shadow address (base 0x6C00)")
    A("\tdb\t0x24,0x25,0x27,0x27,0x28,0x28,0x2a,0x2a,0x2b,0x2b")
    A("")
    A(";  The manufacturer's block map, one table per card (SDK FlashMem.txt): 64 KiB")
    A(";  blocks all the way up, and the LAST 64 KiB split 32 / 8 / 8 / 16. The small")
    A(";  blocks at the top are where every save lives -- that split exists so that")
    A(";  rewriting one save slot does not cost 64 KiB. Absolute addresses, card 0.")
    for name, cap in (("_blk_4m", 0x080000), ("_blk_8m", 0x100000), ("_blk_16m", 0x200000)):
        A(f"{name}:")
        for off in card_block_offsets(cap):
            A(f"\tdl\t{0x200000 + off:#010x}")
    A("")
    A(";  Register-preserving indirect jump used by every ISR trampoline:")
    A(";  save XWA to BIOS scratch RAM, push the user-handler address, restore")
    A(";  XWA, RET -> jumps to the handler with the interrupt frame intact and")
    A(";  every register unchanged. No stack turd, no unsupported EX/CALL form.")
    A("SCRATCH\tequ\t0x006c40")
    A("")
    A("; --- VBlank ISR : latch controller into Sys_Lever, then chain ---")
    A("_isr_vblank:")
    A("\tldl\t(SCRATCH), xwa        ; save XWA")
    A("\tldb\ta, (0x0000b0)          ; controller port")
    A("\tldb\t(0x006f82), a          ; -> Sys_Lever (games read this)")
    A("\tldl\txwa, (0x00006fcc)      ; user VBlank handler")
    A("\tpush\txwa")
    A("\tldl\txwa, (SCRATCH)         ; restore XWA")
    A("\tret                            ; -> user handler (it RETIs)")
    A("")
    A("; --- chain trampolines: forward IRQ to the game's user handler ---")
    # emit one chain routine per user-hooked vector (except vblank, above)
    chain_label = {}
    for idx, slot in sorted(USER_SLOT.items()):
        if idx == 11:
            chain_label[idx] = "_isr_vblank"
            continue
        lbl = f"_chain_{idx:02d}"
        chain_label[idx] = lbl
        A(f"{lbl}:")
        A("\tldl\t(SCRATCH), xwa")
        A(f"\tldl\txwa, ({slot:#08x})")
        A("\tpush\txwa")
        A("\tldl\txwa, (SCRATCH)")
        A("\tret")
    A("")
    A(";===============================================================")
    A("; clean-room font, pre-expanded to 2bpp CHAR-RAM tiles (256 x 16 B)")
    A(";===============================================================")
    A("_font_data:")
    font = build_font_2bpp()
    for off in range(0, len(font), 16):
        row = ", ".join(f"0x{b:02x}" for b in font[off:off + 16])
        A(f"\tdb\t{row}")
    A("")
    A(";===============================================================")
    A("; BIOS system-call table @ 0xFFFE00 (indexed by RW3)")
    A(";===============================================================")
    A("SYSCALL_TBL\tsection code large align=1,1")
    sc_stub = SC_STUB
    for i in range(SYSCALL_SLOTS):
        lbl = sc_stub.get(i, "_sc_ret")
        A(f"\tdl\t{lbl:<10s}       ; {i:#04x}")
    A("")
    A(";===============================================================")
    A("; CPU hardware vector table @ 0xFFFF00 (index*4)")
    A(";===============================================================")
    A("INT_VECTOR\tsection code large align=1,1")
    for i in range(HW_TABLE_SLOTS):
        if i == 0:
            tgt, note = "_boot", "reset / swi0"
        elif i == 1:
            tgt, note = "_swi1", "swi 1 (system call)"
        elif i in SERIAL_ISR:
            tgt, note = SERIAL_ISR[i], "link cable -- the BIOS owns this one"
        elif i in chain_label:
            tgt, note = chain_label[i], f"-> user slot {USER_SLOT[i]:#06x}"
        else:
            tgt, note = "_reti", "unused"
        A(f"\tdl\t{tgt:<12s}       ; {i:#04x} {note}")
    A("")
    A("\tend")
    return "\r\n".join(out) + "\r\n"


